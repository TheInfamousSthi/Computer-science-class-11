# Program 6.5: Compute square, cube, and 4th power
# KEYWORD EXPLANATION:
# ** - Exponentiation operator used to calculate power (base ** exponent).

n = float(input("Enter a number: "))

square = n ** 2
cube = n ** 3
fourth_power = n ** 4

print("Number:", n)
print("Square (n^2):", square)
print("Cube (n^3):", cube)
print("Fourth power (n^4):", fourth_power)
