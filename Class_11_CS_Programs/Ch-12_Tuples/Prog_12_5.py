# Program 12.5: Tuple Unpacking
# KEYWORD EXPLANATION:
# Unpacking allows tuple elements to be bound to positional variables directly in one line.

tup = (101, "Aman", 95.5)

roll_no, name, marks = tup

print("Unpacked values:")
print("Roll No:", roll_no)
print("Name:", name)
print("Marks:", marks)
